-- ==============================================================================
-- FIELDOPS Database Baseline Schema Migration (V1)
-- Target: PostgreSQL 17 / Compatible ANSI SQL
-- Description: Baseline schema definition for FieldOps core operational tables
-- ==============================================================================

-- 1. Customers Table
CREATE TABLE IF NOT EXISTS customers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    company VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL,
    phone VARCHAR(255) NOT NULL,
    city VARCHAR(255) NOT NULL,
    address VARCHAR(255),
    latitude DOUBLE PRECISION,
    longitude DOUBLE PRECISION,
    open_jobs_count INTEGER DEFAULT 0,
    completed_jobs_count INTEGER DEFAULT 0,
    satisfaction_score DOUBLE PRECISION,
    last_service_date TIMESTAMP,
    notes VARCHAR(1000),
    created_at TIMESTAMP,
    updated_at TIMESTAMP
);

-- 2. Users Table
CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    full_name VARCHAR(255) NOT NULL,
    role VARCHAR(255) NOT NULL,
    phone VARCHAR(255),
    organization VARCHAR(255),
    avatar_url VARCHAR(255),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP,
    updated_at TIMESTAMP
);

-- 3. Technicians Table
CREATE TABLE IF NOT EXISTS technicians (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    phone VARCHAR(255) NOT NULL,
    status VARCHAR(255) NOT NULL,
    city VARCHAR(255) NOT NULL,
    latitude DOUBLE PRECISION,
    longitude DOUBLE PRECISION,
    active_jobs_count INTEGER DEFAULT 0,
    completed_jobs_today INTEGER DEFAULT 0,
    satisfaction_rating DOUBLE PRECISION,
    avatar_url VARCHAR(255),
    created_at TIMESTAMP,
    updated_at TIMESTAMP
);

-- 4. Technician Skills Table
CREATE TABLE IF NOT EXISTS technician_skills (
    technician_id BIGINT NOT NULL,
    skill VARCHAR(255) NOT NULL,
    CONSTRAINT fk_technician_skills FOREIGN KEY (technician_id) REFERENCES technicians(id) ON DELETE CASCADE
);

-- 5. Work Orders Table
CREATE TABLE IF NOT EXISTS work_orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    work_order_number VARCHAR(255) NOT NULL UNIQUE,
    title VARCHAR(255) NOT NULL,
    description VARCHAR(2000),
    priority VARCHAR(255) NOT NULL,
    status VARCHAR(255) NOT NULL,
    customer_id BIGINT NOT NULL,
    technician_id BIGINT,
    location_name VARCHAR(255),
    city VARCHAR(255),
    address VARCHAR(255),
    latitude DOUBLE PRECISION,
    longitude DOUBLE PRECISION,
    scheduled_start_time TIMESTAMP,
    scheduled_end_time TIMESTAMP,
    sla_deadline TIMESTAMP,
    completed_at TIMESTAMP,
    estimated_duration_hours DOUBLE PRECISION,
    sla_breach_probability DOUBLE PRECISION,
    technician_eta_minutes INTEGER,
    distance_km DOUBLE PRECISION,
    ai_insight VARCHAR(1000),
    service_notes VARCHAR(2000),
    created_at TIMESTAMP,
    updated_at TIMESTAMP,
    CONSTRAINT fk_work_orders_customer FOREIGN KEY (customer_id) REFERENCES customers(id),
    CONSTRAINT fk_work_orders_technician FOREIGN KEY (technician_id) REFERENCES technicians(id)
);

-- 6. Work Order Skills Table
CREATE TABLE IF NOT EXISTS work_order_skills (
    work_order_id BIGINT NOT NULL,
    skill VARCHAR(255) NOT NULL,
    CONSTRAINT fk_work_order_skills FOREIGN KEY (work_order_id) REFERENCES work_orders(id) ON DELETE CASCADE
);

-- 7. Inventory Items Table
CREATE TABLE IF NOT EXISTS inventory_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku VARCHAR(255) NOT NULL UNIQUE,
    name VARCHAR(255) NOT NULL,
    category VARCHAR(255) NOT NULL,
    available_quantity INTEGER DEFAULT 0,
    reserved_quantity INTEGER DEFAULT 0,
    min_threshold INTEGER DEFAULT 0,
    unit_of_measure VARCHAR(255),
    unit_price DOUBLE PRECISION,
    warehouse_location VARCHAR(255),
    status VARCHAR(255) NOT NULL,
    created_at TIMESTAMP,
    updated_at TIMESTAMP
);

-- 8. Decision Audit Logs Table
CREATE TABLE IF NOT EXISTS decision_audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    work_order_id BIGINT NOT NULL,
    work_order_number VARCHAR(255),
    decision_type VARCHAR(255) NOT NULL,
    recommended_technician_id BIGINT,
    recommended_technician_name VARCHAR(255),
    selected_technician_id BIGINT,
    selected_technician_name VARCHAR(255),
    score INTEGER,
    explanation VARCHAR(2000),
    dispatcher_email VARCHAR(255),
    timestamp TIMESTAMP
);

-- 9. Operational Alerts Table
CREATE TABLE IF NOT EXISTS operational_alerts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alert_type VARCHAR(255) NOT NULL,
    severity VARCHAR(255) NOT NULL,
    status VARCHAR(255) NOT NULL,
    title VARCHAR(255) NOT NULL,
    message VARCHAR(1000) NOT NULL,
    work_order_id BIGINT,
    work_order_number VARCHAR(255),
    technician_id BIGINT,
    technician_name VARCHAR(255),
    acknowledged_by VARCHAR(255),
    acknowledged_at TIMESTAMP,
    resolved_by VARCHAR(255),
    resolved_at TIMESTAMP,
    fingerprint VARCHAR(255),
    created_at TIMESTAMP,
    updated_at TIMESTAMP
);

-- 10. Route Decision Audits Table
CREATE TABLE IF NOT EXISTS route_decision_audits (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    technician_id BIGINT NOT NULL,
    technician_name VARCHAR(255) NOT NULL,
    total_stops INTEGER NOT NULL,
    total_distance_km DOUBLE PRECISION NOT NULL,
    total_duration_minutes INTEGER NOT NULL,
    estimated_fuel_saved_liters DOUBLE PRECISION,
    route_json VARCHAR(4000),
    timestamp TIMESTAMP NOT NULL
);

-- 11. Scenario Decision Audits Table
CREATE TABLE IF NOT EXISTS scenario_decision_audits (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scenario_type VARCHAR(255) NOT NULL,
    description VARCHAR(2000) NOT NULL,
    dispatcher_email VARCHAR(255) NOT NULL,
    affected_work_order_id BIGINT,
    affected_technician_id BIGINT,
    applied_at TIMESTAMP NOT NULL,
    rollback_supported BOOLEAN NOT NULL DEFAULT TRUE,
    rolled_back BOOLEAN NOT NULL DEFAULT FALSE,
    rolled_back_at TIMESTAMP,
    snapshot_json VARCHAR(4000)
);

-- 12. Model Registry Entries Table
CREATE TABLE IF NOT EXISTS model_registry_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    model_key VARCHAR(255) NOT NULL UNIQUE,
    model_name VARCHAR(255) NOT NULL,
    model_version VARCHAR(255) NOT NULL,
    algorithm VARCHAR(255) NOT NULL,
    trained_at TIMESTAMP,
    loaded_at TIMESTAMP,
    primary_metric_name VARCHAR(255),
    primary_metric_value DOUBLE PRECISION,
    secondary_metric_name VARCHAR(255),
    secondary_metric_value DOUBLE PRECISION,
    evaluation_dataset VARCHAR(500),
    synthetic_disclaimer VARCHAR(500)
);

-- 13. Notifications Table
CREATE TABLE IF NOT EXISTS notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type VARCHAR(255) NOT NULL,
    title VARCHAR(255) NOT NULL,
    message VARCHAR(1000) NOT NULL,
    target_role VARCHAR(255),
    recipient_email VARCHAR(255),
    read BOOLEAN NOT NULL DEFAULT FALSE,
    action_url VARCHAR(255),
    created_at TIMESTAMP NOT NULL
);

-- Indexes for performance
CREATE INDEX IF NOT EXISTS idx_alert_fingerprint ON operational_alerts (fingerprint);
CREATE INDEX IF NOT EXISTS idx_alert_severity ON operational_alerts (severity);
CREATE INDEX IF NOT EXISTS idx_alert_status ON operational_alerts (status);
CREATE INDEX IF NOT EXISTS idx_alert_tech ON operational_alerts (technician_id);
CREATE INDEX IF NOT EXISTS idx_alert_timestamp ON operational_alerts (created_at);
CREATE INDEX IF NOT EXISTS idx_alert_type ON operational_alerts (alert_type);
CREATE INDEX IF NOT EXISTS idx_alert_work_order ON operational_alerts (work_order_id);
CREATE INDEX IF NOT EXISTS idx_route_audit_tech ON route_decision_audits (technician_id);
CREATE INDEX IF NOT EXISTS idx_route_audit_timestamp ON route_decision_audits (timestamp);
CREATE INDEX IF NOT EXISTS idx_scenario_dispatcher ON scenario_decision_audits (dispatcher_email);
CREATE INDEX IF NOT EXISTS idx_scenario_timestamp ON scenario_decision_audits (applied_at);
CREATE INDEX IF NOT EXISTS idx_scenario_type ON scenario_decision_audits (scenario_type);
CREATE INDEX IF NOT EXISTS idx_work_orders_customer ON work_orders (customer_id);
CREATE INDEX IF NOT EXISTS idx_work_orders_technician ON work_orders (technician_id);
CREATE INDEX IF NOT EXISTS idx_work_orders_status ON work_orders (status);
CREATE INDEX IF NOT EXISTS idx_work_orders_created_at ON work_orders (created_at);
